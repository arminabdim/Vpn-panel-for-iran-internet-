  const I18N = {
    get lang() {
      return current;
    },
    get rtl() {
      return current === 'fa';
    },
    set(lang) {
      if (!STRINGS[lang]) return;
      current = lang;
      try {
        localStorage.setItem('openpath.lang', lang);
      } catch (e) {
        /* ignore */
      }
    },
    t(key) {
      const table = STRINGS[current] || STRINGS.en;
      return table[key] !== undefined ? table[key] : STRINGS.en[key] !== undefined ? STRINGS.en[key] : key;
    },
    // methods carry {en, fa} objects
    pick(value) {
      if (value === undefined || value === null) return '';
      if (typeof value === 'string') return value;
      return value[current] !== undefined ? value[current] : value.en || '';
    },
    STRINGS,
  };

  global.I18N = I18N;
